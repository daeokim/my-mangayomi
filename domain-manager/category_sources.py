"""Build standalone Mangayomi category sources from the maintained TV engines.

Mangayomi loads one script per source; it cannot import a sibling engine.
Generated scripts are committed for direct installation, never edited by hand.
"""
import re

GROUPS = {
    'variety': ('예능', ['ent', 'ott_ent', 'old_ent']),
    'movie': ('영화', ['movie', 'kor_movie']),
    'drama': ('드라마', ['drama', 'world', 'short_drama', 'old_drama']),
    'anime': ('애니', ['animation', 'ani_movie']),
}


def build_categories(root, changes, entries, readme):
    for site, title in [('tvroom', '티비룸'), ('tvwiki', '티비위키')]:
        engine_path = f'javascript/anime/{site}.js'
        engine_entry = next((e for e in entries if e['sourceCodeUrl'].endswith('/' + engine_path)), None)
        if not engine_entry:
            continue
        for group, (label, boards) in GROUPS.items():
            path = f'javascript/anime/{site}-{group}.js'
            entry = next((e for e in entries if e['sourceCodeUrl'].endswith('/' + path)), None)
            if not entry:
                continue
            code = changes.get(engine_path, (root / engine_path).read_text())
            code = code.replace('DefaultExtension', 'TvCategoryEngine')
            code = re.sub(r'(\bname:\s*")[^"]+', lambda m: m[1] + title + ' · ' + label, code, count=1)
            code = code.replace(f'anime/src/ko/{site}.js', f'anime/src/ko/{site}-{group}.js')
            code = '// Generated by domain-manager/category_sources.py; edit the engine/template instead.\n' + code
            template = (root / f'javascript/templates/{site}-category.js').read_text()
            code += '\n' + template.replace('__GROUP__', group).replace('__BOARDS__', repr(boards))
            if not (root / path).is_file() or code != (root / path).read_text():
                changes[path] = code
            entry['baseUrl'] = engine_entry['baseUrl']
            entry['version'] = engine_entry['version']
            row = f"| {entry['name']} | {entry['version']} | {entry['baseUrl']} | {entry['appMinVerReq']} |"
            readme = re.sub(r'^\| ' + re.escape(entry['name']) + r' \| [^\n]+$', lambda _: row, readme, count=1, flags=re.M)
    return readme
