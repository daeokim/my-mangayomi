"""Render the standalone JS files shipped to Mangayomi (no runtime imports)."""
import json
import re
from pathlib import Path
import category_sources


def build_anime(root, changes, entries):
    for site in ('ani24', 'anilife'):
        path = f'javascript/anime/{site}.js'
        entry = next((e for e in entries if e['sourceCodeUrl'].endswith('/' + path)), None)
        if not entry:
            continue
        meta = {k: entry[k] for k in ('name', 'lang', 'baseUrl', 'apiUrl', 'iconUrl', 'typeSource', 'itemType', 'isNsfw', 'hasCloudflare', 'version', 'dateFormat', 'dateFormatLocale')}
        meta.update(pkgPath=f'anime/src/ko/{site}.js', notes=entry.get('notes', ''))
        header = re.sub(r'^(\s*)"(\w+)":', r'\1\2:', json.dumps([meta], ensure_ascii=False, indent=2), flags=re.M)
        code = ('// Generated by domain-manager/build_sources.py; edit javascript/templates instead.\n'
                'const mangayomiSources = ' + header + ';\n\n'
                + (root / 'javascript/templates/anime-common.js').read_text() + '\n'
                + (root / f'javascript/templates/{site}-body.js').read_text())
        if not (root / path).is_file() or (root / path).read_text() != code:
            changes[path] = code


def main():
    root = Path(__file__).resolve().parents[1]
    catalog = root / 'anime_index.json'
    entries = json.loads(catalog.read_text())
    changes = {}
    before = json.dumps(entries, ensure_ascii=False)
    readme = (root / 'README.md').read_text()
    updated = category_sources.build_categories(root, changes, entries, readme)
    build_anime(root, changes, entries)
    if updated != readme:
        changes['README.md'] = updated
    if json.dumps(entries, ensure_ascii=False) != before:
        changes['anime_index.json'] = json.dumps(entries, ensure_ascii=False, indent=2) + '\n'
    for path, code in changes.items():
        (root / path).write_text(code)
    print('Generated:', ', '.join(changes) or 'already current')


if __name__ == '__main__':
    main()
